/**
 * The Zharp Godot addon, vendored into the CLI so `zharp init` can copy it into a Godot project
 * without a download: writes src/init/godot-addon.ts from a zharp-godot checkout.
 *
 *     node scripts/vendor-godot-addon.mjs ../../../zharp-godot-sdk
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = process.argv[2];
if (!root) throw new Error('usage: vendor-godot-addon.mjs <zharp-godot checkout>');
const addon = join(root, 'addons', 'zharp');
const version = /version="([^"]+)"/.exec(readFileSync(join(addon, 'plugin.cfg'), 'utf8'))[1];
const files = {};
(function walk(dir) {
  for (const name of readdirSync(dir).sort()) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path);
    else if (!name.endsWith('.uid') && !name.endsWith('.import')) files[`addons/zharp/${relative(addon, path).split(sep).join('/')}`] = readFileSync(path, 'utf8').replace(/\r\n/g, '\n');
  }
})(addon);
const out = fileURLToPath(new URL('../src/init/godot-addon.ts', import.meta.url));
writeFileSync(out, [
  '// Generated by scripts/vendor-godot-addon.mjs from zharp-godot: do not edit.',
  `export const GODOT_ADDON_VERSION = ${JSON.stringify(version)};`,
  `export const GODOT_ADDON: Record<string, string> = ${JSON.stringify(files, null, 2)};`,
  '',
].join('\n'));
console.log(`addons/zharp ${version}: ${Object.keys(files).length} files`);
